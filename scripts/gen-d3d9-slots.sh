#!/bin/sh
# Writes the D3D9 vtable slot lists the metal backend is built against.
#
# The bridge finds a host method by its index in the null device's tables
# (shims/d3d9_null.c, the k_* arrays), so those tables are the one
# definition of the slot order. This reads them from the patched porter
# tree instead of restating them, and emits one X macro per interface:
#
#   #define MTL_SLOTS_IDirect3D9(X) X(IDirect3D9, QueryInterface, 0) ...
#   #define MTL_NSLOTS_IDirect3D9 17
#
# Usage: gen-d3d9-slots.sh PATH/TO/d3d9_null.c OUT.h
set -eu
src=$1
out=$2
tmp=$out.tmp
{
    echo "/* Generated by scripts/gen-d3d9-slots.sh from shims/d3d9_null.c. */"
    echo "#ifndef MTL_D3D9_SLOTS_H"
    echo "#define MTL_D3D9_SLOTS_H"
    awk '
        /^static const rt_shim k_[a-z0-9]+\[\] = \{/ { in_table = 1; n = 0; iface = ""; next }
        in_table && /^\};/ {
            printf "\n#define MTL_NSLOTS_%s %d\n", iface, n
            in_table = 0
            next
        }
        in_table && /"d3d9\.dll", "IDirect3D[A-Za-z0-9]*::[A-Za-z0-9]*"/ {
            match($0, /"IDirect3D[A-Za-z0-9]*::[A-Za-z0-9]*"/)
            name = substr($0, RSTART + 1, RLENGTH - 2)
            split(name, part, "::")
            if (iface == "") {
                iface = part[1]
                printf "\n#define MTL_SLOTS_%s(X) \\\n", iface
            }
            printf "    X(%s, %s, %d) \\\n", part[1], part[2], n
            n++
        }
    ' "$src"
    echo
    echo "#endif"
} > "$tmp"
# Every macro body above ends in a backslash; the blank line after it
# closes the macro, which awk already wrote before each count line.
mv "$tmp" "$out"
